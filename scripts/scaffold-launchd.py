#!/usr/bin/env python3
"""Generate a project-owned child adapter for an existing user LaunchAgent; never starts it."""
import argparse
import json
from pathlib import Path
import re
import shutil
import tempfile


def scaffold(project, child, name, label, profile=None):
    project = Path(project).resolve()
    destination = (project / child).resolve()
    if Path(child).is_absolute() or not destination.is_relative_to(project) or destination == project:
        raise ValueError('Child must be a strict project descendant')
    if not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]+', label):
        raise ValueError('Invalid launchd label')
    if profile is not None and not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]*', profile):
        raise ValueError('Invalid tunnel profile')
    manifest_path = project / 'control-panel.json'
    parent = json.loads(manifest_path.read_text())
    if destination.exists():
        raise ValueError('Child directory already exists; inspect it before updating')
    relative = destination.relative_to(project).as_posix()
    children = parent.setdefault('children', [])
    if any(item['path'] == relative for item in children):
        raise ValueError('Child is already declared')
    template = Path(__file__).resolve().parent.parent / 'templates/launchd/service.py'
    # Assemble the complete child before adding the discovery reference.
    destination.parent.mkdir(parents=True, exist_ok=True)
    staging = Path(tempfile.mkdtemp(prefix='.launchd-scaffold-', dir=destination.parent))
    try:
        scripts = staging / 'scripts'
        scripts.mkdir()
        shutil.copy2(template, scripts / 'service.py')
        for action in ('start', 'stop', 'status', 'restart'):
            wrapper = scripts / (action + '.sh')
            wrapper.write_text('#!/bin/bash\nset -euo pipefail\ncd "$(dirname "$0")/.."\nexec python3 scripts/service.py ' + action + ' "$@"\n')
            wrapper.chmod(0o755)
        config = {'label': label, 'plist': '~/Library/LaunchAgents/' + label + '.plist'}
        if profile:
            config['probe'] = {'type': 'tunnel-client', 'profile': profile}
        (staging / 'launchd.json').write_text(json.dumps(config, indent=2) + '\n')
        manifest = {'id': str(parent.get('id', project.name)) + '-' + destination.name,
                    'name': name, 'workingDirectory': '.', 'surfaceType': 'service',
                    'runtimeMode': 'packaged', 'processMode': 'external', 'processManager': 'launchd',
                    'notes': '所属项目的独立子服务；由已有 LaunchAgent 管理。状态区分进程运行与本地就绪，远端 MCP 可用性需实际调用验证。'}
        for action in ('start', 'stop', 'status', 'restart'):
            manifest[action + 'Command'] = './scripts/' + action + '.sh'
        (staging / 'control-panel.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
        (staging / 'README.md').write_text('''# Project-owned LaunchAgent adapter

Generated by project-tooling `scripts/scaffold-launchd.py`. This directory belongs to the parent
project. The parent declares it in `children`; parent lifecycle scripts do not control it.

`launchd.json` identifies an existing per-user LaunchAgent. Install/provision that agent separately;
this adapter never creates credentials, tunnel profiles or launchd definitions. Missing or mismatched
configuration fails visibly. Do not commit tunnel profile contents or secrets.

Run `./scripts/{start,stop,status,restart}.sh` from this directory. Status supports `--json`.
Start reuses a running job or bootstraps the existing plist. Stop uses bootout to unload KeepAlive
jobs; restart performs stop then start. It does not change RunAtLoad or future-login behavior.
Recovery helpers must respect an unloaded target and must never bootstrap a deliberately stopped job.

Tunnel readiness is a local health/ready/control-plane-poll check using the exact launchd PID and
its loopback listener, not proof of a successful remote MCP tool call. No public metrics endpoint
or fixed port is invented; tunnel-client owns its ephemeral loopback admin port.
''')
        staging.rename(destination)
        children.append({'path': relative, 'role': 'tunnel' if profile else 'service',
                         'notes': '项目自有的外部进程子服务；独立启停，不随父项目重复控制'})
        with tempfile.NamedTemporaryFile(mode='w', dir=project, prefix='.control-panel-', delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(json.dumps(parent, ensure_ascii=False, indent=2) + '\n')
        temporary.chmod(manifest_path.stat().st_mode & 0o777)
        temporary.replace(manifest_path)
    finally:
        if staging.exists():
            shutil.rmtree(staging)
    return destination


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--project', required=True)
    parser.add_argument('--child', default='tooling/tunnel')
    parser.add_argument('--name', required=True)
    parser.add_argument('--label', required=True)
    parser.add_argument('--tunnel-profile')
    args = parser.parse_args()
    try:
        print(scaffold(args.project, args.child, args.name, args.label, args.tunnel_profile))
    except (OSError, ValueError, KeyError) as error:
        parser.exit(1, str(error) + '\n')


if __name__ == '__main__':
    main()
